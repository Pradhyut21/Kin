import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'
const url = process.env.KIN_BASE_URL ?? 'http://127.0.0.1:5173'
const routeUrl = route => `${url.replace(/\/$/, '')}/#/${route.replace(/^\//, '')}`
const output = path.resolve('artifacts')
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: process.env.KIN_BROWSER_CHANNEL ?? 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1024 }, locale: 'en-GB' })
const page = await context.newPage()
await page.emulateMedia({ reducedMotion: 'reduce' })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('kin.demo.v3')))
const invariant = state => assert.equal(state.available + state.locked + state.spent, state.contributed)
const step = label => console.log(`PASS ${label}`)
async function goHome() { await page.goto(url); await page.getByRole('heading', { name: /Hey Priya|Peace of mind/ }).waitFor() }
try {
  await goHome()
  const routeBeforeSkip = new URL(page.url()).hash
  await page.locator('.skip-link').focus()
  await page.keyboard.press('Enter')
  assert.equal(new URL(page.url()).hash, routeBeforeSkip)
  assert.equal(await page.locator('#main').evaluate(el => document.activeElement === el), true)
  step('skip link focuses content without changing the hash route')
  await page.screenshot({ path: path.join(output, 'kin-overview-desktop.png'), fullPage: true })
  assert.equal(await page.locator('body').evaluate(el => el.scrollWidth <= innerWidth), true)
  invariant(await saved()); step('desktop dashboard, demo disclosure, and conserved initial ledger')
  await page.getByRole('link', { name: /The everyday shop/ }).click()
  await page.getByRole('button', { name: /Confirm demo payment/ }).click()
  await page.getByRole('heading', { name: 'Demo paid' }).waitFor()
  let state = await saved(); assert.equal(state.spent, 2860); assert.equal(state.week.spent.groceries, 2860); invariant(state)
  await page.screenshot({ path: path.join(output, 'kin-payment-receipt.png'), fullPage: true })
  step('Tesco confirmation updates balance, category, and evaluation receipt')
  await goHome()
  await page.getByRole('link', { name: /A bigger little purchase/ }).click()
  await page.getByRole('button', { name: /Ask Mom · no charge yet/ }).click()
  await page.getByRole('heading', { name: 'Needs Mom' }).waitFor()
  state = await saved(); assert.equal(state.spent, 2860); assert.equal(state.intents.filter(i => i.status === 'pending').length, 1); invariant(state)
  await page.getByRole('link', { name: 'View Mom’s inbox' }).click()
  assert.equal(await page.getByRole('button', { name: 'Approve demo payment' }).isDisabled(), true)
  await page.locator('.role-switch').getByRole('button', { name: 'Mom', exact: true }).click()
  // A rule can change while a request waits. A rejected approval must remain retryable.
  async function setPaymentCap(value) {
    await page.goto(routeUrl('/rules'))
    await page.locator('.rule-editor').getByRole('combobox').selectOption('paymentCap')
    await page.locator('.rule-editor').getByRole('textbox').first().fill(value)
    await page.getByRole('button', { name: 'Review change' }).click()
    await page.getByRole('button', { name: 'Apply reviewed rule' }).click()
  }
  await setPaymentCap('200')
  await page.goto(routeUrl('/approvals'))
  await page.getByRole('button', { name: 'Check & reject' }).click()
  await page.getByRole('heading', { name: 'Blocked', exact: true }).waitFor()
  state = await saved(); assert.equal(state.spent, 2860); assert.equal(state.intents.filter(i => i.status === 'pending').length, 1)
  assert.equal(await page.getByRole('button', { name: 'Check & reject' }).count(), 1)
  await setPaymentCap('1000')
  await page.goto(routeUrl('/approvals'))
  await page.getByRole('button', { name: 'Approve demo payment' }).click()
  await page.getByRole('heading', { name: 'Demo paid' }).waitFor()
  state = await saved(); assert.equal(state.spent, 27760); assert.equal(state.week.spent.technology, 24900); invariant(state)
  await page.screenshot({ path: path.join(output, 'kin-parent-approval.png'), fullPage: true })
  step('Apple request is uncharged until explicit parent approval')
  step('denied parent approval stays in inbox and succeeds once after correcting the cap')
  await page.locator('.role-switch').getByRole('button', { name: 'Priya', exact: true }).click()
  await goHome()
  await page.getByRole('link', { name: /A line we don’t cross/ }).click()
  await page.getByRole('button', { name: 'Record blocked attempt' }).click()
  await page.getByRole('heading', { name: 'Blocked', exact: true }).waitFor()
  state = await saved(); assert.equal(state.spent, 27760); assert.equal(state.intents[0].status, 'blocked'); invariant(state)
  step('blocked recipient records a rejected receipt without charging')
  await page.goto(routeUrl('/rules'))
  await page.getByPlaceholder('Set groceries budget to $150').fill('Set groceries budget to $150')
  await page.getByRole('button', { name: 'Create review proposal' }).click()
  assert.equal((await saved()).rules.weeklyCaps.groceries, 12000)
  assert.equal(await page.getByRole('button', { name: 'Apply reviewed rule' }).isDisabled(), true)
  await page.locator('.role-switch').getByRole('button', { name: 'Mom', exact: true }).click()
  await page.getByRole('button', { name: 'Apply reviewed rule' }).click()
  state = await saved(); assert.equal(state.rules.weeklyCaps.groceries, 15000); assert.equal(state.week.spent.groceries, 2860); invariant(state)
  step('plain-language rule remains a review proposal until parent confirmation')
  await page.reload()
  assert.equal((await saved()).rules.weeklyCaps.groceries, 15000)
  await page.goto(routeUrl('/activity'))
  await page.getByRole('button', { name: 'View receipt for Family rule updated' }).first().click()
  await page.getByRole('region', { name: 'Evaluation receipt' }).waitFor()
  assert.equal((await saved()).spent, 27760); step('reload restores rules and consistent activity ledger')
  await page.goto(routeUrl('/testnet'))
  await page.getByRole('heading', { name: 'Verify the money rules.' }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Connect wallet', exact: true }).isDisabled(), true)
  assert.equal(await page.getByRole('button', { name: 'Create funded stream' }).isDisabled(), true)
  assert.equal(await page.getByRole('button', { name: 'Confirm payment in wallet' }).isDisabled(), true)
  await page.screenshot({ path: path.join(output, 'kin-testnet-disabled.png'), fullPage: true })
  step('testnet writes gated without a wallet; no fake transaction success')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('.role-switch').getByRole('button', { name: 'Priya', exact: true }).click()
  await goHome()
  assert.equal(await page.locator('body').evaluate(el => el.scrollWidth <= innerWidth), true)
  await page.getByRole('navigation', { name: 'Mobile navigation' }).waitFor()
  await page.screenshot({ path: path.join(output, 'kin-overview-mobile.png'), fullPage: true })
  await page.screenshot({ path: path.join(output, 'kin-overview-mobile-screen.png') })
  for (const route of ['chat', 'rules', 'approvals', 'activity', 'add-money', 'testnet', 'onboarding']) {
    await page.goto(routeUrl(route))
    await page.reload()
    assert.equal(await page.locator('body').evaluate(el => el.scrollWidth <= innerWidth), true, `Mobile overflow on ${route}`)
  }
  step('all eight routes fit a 390px mobile viewport')
  // Block external network access, then exercise a payment. The demo has no API requirement.
  await page.route('**/*', route => new URL(route.request().url()).origin === new URL(url).origin ? route.continue() : route.abort())
  await page.goto(routeUrl('/chat'))
  await page.locator('#payment-amount').fill('1.25')
  await page.getByRole('button', { name: 'Review payment', exact: true }).click()
  await page.getByRole('button', { name: /Confirm demo payment/ }).click()
  await page.getByRole('heading', { name: 'Demo paid' }).waitFor()
  state = await saved(); assert.equal(state.spent, 27885); invariant(state)
  step('payment works with all external network requests blocked')
  await page.locator('#payment-amount').fill('-10')
  await page.locator('#payment-amount').press('Enter')
  await page.getByRole('alert').getByText('Enter a positive amount with at most two decimal places.').waitFor()
  assert.equal((await saved()).spent, 27885)
  step('keyboard form submission rejects invalid amounts without changing ledger')
  await goHome()
  await page.locator('.role-switch').getByRole('button', { name: 'Mom', exact: true }).click()
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  assert.equal((await saved()).stream.paused, true)
  await page.locator('.role-switch').getByRole('button', { name: 'Priya', exact: true }).click()
  await page.goto(routeUrl('/chat?story=groceries'))
  await page.getByRole('button', { name: 'Record blocked attempt' }).click()
  state = await saved(); assert.equal(state.spent, 27885); assert.equal(state.receipts[0].checks[0].name, 'Allowance status')
  await goHome()
  await page.locator('.role-switch').getByRole('button', { name: 'Mom', exact: true }).click()
  await page.getByRole('button', { name: 'Resume', exact: true }).click()
  assert.equal((await saved()).stream.paused, false)
  step('parent pause freezes student spending and resume restores flow')
  await page.getByRole('link', { name: 'Add sample credits', exact: true }).click()
  await page.getByRole('button', { name: 'Review sample top-up' }).click()
  const contribution = (await saved()).contributed
  await page.getByRole('button', { name: 'Confirm sample contribution' }).click()
  state = await saved(); assert.equal(state.contributed, contribution + 25000); invariant(state)
  step('parent sample funding adds only reserved credits with explicit confirmation')
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click()
  await page.getByRole('dialog', { name: 'A fresh family story?' }).waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('dialog').count(), 0)
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Reset demo', exact: true }).click()
  state = await saved(); assert.equal(state.spent, 0); assert.equal(state.contributed, 244250); assert.equal(state.receipts.length, 1); invariant(state)
  step('reset is keyboard accessible and restores the complete shared demo')
  assert.deepEqual(errors, [], 'Browser runtime errors')
  console.log(`Browser acceptance passed. Screenshots: ${output}`)
} finally { await context.close(); await browser.close() }
